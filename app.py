def predict_misuse(
    age,
    dose,
    prior_abx,
    fever,
    diagnosis_text,
    meds,
    ui_lang
):

    try:

        age = float(age or 0)
        dose = float(dose or 0)
        prior_abx = int(prior_abx or 0)
        fever = int(fever or 0)

    except Exception:

        return "❌ Please enter valid numeric values."


    diagnosis_text = str(
        diagnosis_text or ""
    ).strip()

    meds = str(
        meds or "none"
    ).strip()

    diagnosis_lower = diagnosis_text.lower()
    meds_lower = meds.lower()


    misuse_type = ""


    # ---------------------------------
    # Rule 1
    # ---------------------------------

    if (
        "viral" in diagnosis_lower
        and meds_lower not in [
            "none",
            "",
            "na",
            "no"
        ]
    ):

        misuse_type = (
            "Antibiotic recorded for a likely "
            "viral infection."
        )


    # ---------------------------------
    # Rule 2
    # ---------------------------------

    elif (
        "pneumonia" in diagnosis_lower
        and meds_lower in [
            "none",
            "",
            "na",
            "no"
        ]
    ):

        misuse_type = (
            "No antibiotic is recorded for "
            "a pneumonia case."
        )


    # ---------------------------------
    # Rule 3
    # ---------------------------------

    elif dose > 40:

        misuse_type = (
            "Dose exceeds the prototype's "
            "configured safety threshold."
        )


    # ---------------------------------
    # ML
    # ---------------------------------

    else:

        input_data = pd.DataFrame(
            [[
                age,
                dose,
                prior_abx,
                fever
            ]],
            columns=FEATURE_COLUMNS
        )

        prediction = model.predict(
            input_data
        )[0]

        if prediction == 1:

            misuse_type = (
                "Potential antibiotic misuse "
                "detected by the ML model."
            )

        else:

            misuse_type = (
                "No misuse pattern detected "
                "by the prototype."
            )


    # ========================================================
    # RESULT
    # ========================================================

    is_misuse = (
        "No misuse pattern" not in misuse_type
    )


    if ui_lang == "Hindi":

        if is_misuse:

            result_title = "⚠️ संभावित दुरुपयोग पाया गया"

            recommendation = (
                "प्रिस्क्रिप्शन की चिकित्सकीय समीक्षा करें "
                "और स्थानीय अस्पताल/क्लिनिकल प्रोटोकॉल "
                "का पालन करें।"
            )

        else:

            result_title = "✅ कोई स्पष्ट दुरुपयोग पैटर्न नहीं"

            recommendation = (
                "इस प्रोटोटाइप के अनुसार कोई स्पष्ट "
                "दुरुपयोग पैटर्न नहीं मिला। अंतिम निर्णय "
                "योग्य चिकित्सक द्वारा किया जाना चाहिए।"
            )

    else:

        if is_misuse:

            result_title = (
                "⚠️ Potential Misuse Detected"
            )

            recommendation = (
                "Review the prescription clinically "
                "and follow applicable hospital or "
                "clinical guidelines."
            )

        else:

            result_title = (
                "✅ No Clear Misuse Pattern"
            )

            recommendation = (
                "No clear misuse pattern was detected "
                "by this prototype. Final clinical decisions "
                "must be made by a qualified healthcare professional."
            )


    result = f"""
### {result_title}

**Reason:**
{misuse_type}

**Recommendation:**
{recommendation}

---

⚠️ **Important:** This system is a research/educational prototype and must not replace professional medical judgment.
"""


    # ========================================================
    # SAVE LOG
    # ========================================================

    log_entry = pd.DataFrame(
        [{
            "timestamp":
                datetime.now().strftime(
                    "%Y-%m-%d %H:%M:%S"
                ),

            "user":
                SESSION.get("username"),

            "role":
                SESSION.get("role"),

            "age":
                age,

            "dose_mg_per_kg":
                dose,

            "prior_abx_30d":
                prior_abx,

            "fever_flag":
                fever,

            "diagnosis_text":
                diagnosis_text,

            "meds":
                meds,

            "prediction":
                result_title,

            "reason":
                misuse_type
        }]
    )


    if os.path.exists(LOG_FILE):

        log_entry.to_csv(
            LOG_FILE,
            mode="a",
            header=False,
            index=False
        )

    else:

        log_entry.to_csv(
            LOG_FILE,
            index=False
        )


    return result


