import pandas as pd

def build_features(df: pd.DataFrame):
    """
    Build simple tabular features used by the prototype model.
    Expect df columns: age, diagnosis_text, meds, dose_mg_per_kg, prior_abx_30d, fever_flag
    """
    X = pd.DataFrame()
    X['age'] = df['age'].astype(float)
    X['prior_abx_30d'] = df.get('prior_abx_30d', pd.Series([0]*len(df))).astype(float)
    X['fever_flag'] = df.get('fever_flag', pd.Series([0]*len(df))).astype(float)
    X['is_child'] = (X['age'] < 18).astype(int)

    # Does the record include any antibiotic?
    def has_antibiotic(meds):
        if pd.isna(meds): return 0
        s = str(meds).lower()
        if s.strip() in ('', 'none', 'na', 'no'): return 0
        return 1
    X['has_antibiotic'] = df['meds'].apply(has_antibiotic)

    # Simple diagnosis flags
    def diag_common_cold(text):
        if pd.isna(text): return 0
        return 1 if 'cold' in str(text).lower() else 0
    X['diag_common_cold'] = df['diagnosis_text'].apply(diag_common_cold)

    # dose mg/kg numeric
    X['dose_mg_per_kg'] = df.get('dose_mg_per_kg', pd.Series([0]*len(df))).fillna(0).astype(float)

    return X

