def predict_misuse(age,dose,prior_abx,fever,diagnosis_text,meds,ui_lang="English"):
    misuse_type = ""
    if "viral" in diagnosis_text.lower() and meds != "none":
        misuse_type = "Antibiotic for viral infection"
    elif "pneumonia" in diagnosis_text.lower() and meds=="none":
        misuse_type = "Missing antibiotic for bacterial infection"
    elif dose>40:
        misuse_type = "Overdose detected"
    else:
        data = pd.DataFrame([[age,dose,prior_abx,fever]],columns=["age","dose_mg_per_kg","prior_abx_30d","fever_flag"])
        pred = model.predict(data)[0]
        misuse_type = "AI-detected misuse" if pred==1 else "Appropriate use"

    rec_en = {"viral":"Avoid antibiotics; rest, fluids, paracetamol.",
              "pneumonia":"Use amoxicillin or azithromycin under prescription.",
              "overdose":"Reduce antibiotic dose to 10–20 mg/kg.",
              "ok":"Antibiotic usage seems appropriate."}
    rec_hi = {"viral":"एंटीबायोटिक्स से बचें; आराम करें, तरल पदार्थ लें, पैरासिटामॉल लें।",
              "pneumonia":"एमॉक्सिसिलिन या एजिथ्रोमाइसिन का प्रयोग करें।",
              "overdose":"खुराक 10–20 mg/kg तक कम करें।",
              "ok":"एंटीबायोटिक उपयोग उपयुक्त है।"}
    rec_dict = rec_en if ui_lang=="English" else rec_hi

    if "viral" in diagnosis_text.lower():
        recommendation = rec_dict["viral"]
    elif "pneumonia" in diagnosis_text.lower():
        recommendation = rec_dict["pneumonia"]
    elif dose>40:
        recommendation = rec_dict["overdose"]
    else:
        recommendation = rec_dict["ok"]

    result = f"**Result:** {'⚠️ Misuse Detected' if 'misuse' in misuse_type.lower() else '✅ Appropriate Use'}\n\n" \
             f"**Reason:** {misuse_type}\n\n**Recommendation:** {recommendation}"

    if "misuse" in misuse_type.lower() or dose>40:
        alert_msg = "🚨 ALERT: Check prescription carefully!" if ui_lang=="English" else "🚨 चेतावनी: कृपया प्रिस्क्रिप्शन जांचें!"
        result += f"\n\n{alert_msg}"

    log_entry = pd.DataFrame([{
        "timestamp": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "user": SESSION["username"],
        "role": SESSION["role"],
        "age": age,
        "dose_mg_per_kg": dose,
        "prior_abx_30d": prior_abx,
        "fever_flag": fever,
        "diagnosis_text": diagnosis_text,
        "meds": meds,
        "prediction": result
    }])
    if os.path.exists("aamd_logs.csv"):
        log_entry.to_csv("aamd_logs.csv",mode="a",header=False,index=False)
    else:
        log_entry.to_csv("aamd_logs.csv",index=False)

    return result

