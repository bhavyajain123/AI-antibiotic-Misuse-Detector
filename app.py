def dashboard():

    if not os.path.exists(LOG_FILE):

        return (
            "### Dashboard Summary\n\n"
            "No prediction data available yet.",
            None,
            pd.DataFrame()
        )


    logs = pd.read_csv(
        LOG_FILE
    )


    if logs.empty:

        return (
            "### Dashboard Summary\n\n"
            "No prediction data available yet.",
            None,
            logs
        )


    total = len(logs)


    if "prediction" in logs.columns:

        misuse_count = logs[
            "prediction"
        ].astype(str).str.contains(
            "Misuse",
            case=False,
            na=False
        ).sum()

    else:

        misuse_count = 0


    misuse_rate = round(
        (misuse_count / total) * 100,
        2
    )


    # ========================================================
    # CHART
    # ========================================================

    chart_path = "misuse_chart.png"


    plt.figure(
        figsize=(6, 4)
    )


    proper_count = total - misuse_count


    labels = [
        "Potential Misuse",
        "No Clear Misuse"
    ]

    values = [
        misuse_count,
        proper_count
    ]


    plt.pie(
        values,
        labels=labels,
        autopct="%1.1f%%"
    )

    plt.title(
        "Prescription Analysis"
    )

    plt.tight_layout()

    plt.savefig(
        chart_path
    )

    plt.close()


    summary = f"""
## 📊 Dashboard Summary

**Total Predictions:** {total}

**Potential Misuse Cases:** {misuse_count}

**No Clear Misuse Cases:** {proper_count}

**Potential Misuse Rate:** {misuse_rate}%

> This dashboard shows prototype analysis results and should not be treated as clinical statistics.
"""


    return (
        summary,
        chart_path,
        logs
    )


