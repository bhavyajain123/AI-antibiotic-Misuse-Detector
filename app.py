def dashboard():
    if not os.path.exists("aamd_logs.csv"):
        return "No data yet.", None, None
    df_logs = pd.read_csv("aamd_logs.csv")
    total=len(df_logs)
    misuse = df_logs["prediction"].str.contains("Misuse").sum()
    misuse_rate = round((misuse/total)*100,2)
    plt.figure(figsize=(6,4))
    df_logs["prediction"].str.contains("Misuse").value_counts().plot(kind="pie",autopct="%1.1f%%")
    plt.title("Misuse vs Proper Use")
    plt.tight_layout()
    chart_path="misuse_chart.png"
    plt.savefig(chart_path)
    plt.close()
    summary=f"### Dashboard Summary\n- Total: {total}\n- Misuse: {misuse}\n- Misuse Rate: {misuse_rate}%"
    return summary, chart_path, df_logs

def generate_pdf(name,age,dose,diagnosis,meds,result):
    pdf=FPDF()
    pdf.add_page()
    pdf.set_font("Arial","B",16)
    pdf.cell(0,10,"Patient Report",ln=True,align="C")
    pdf.set_font("Arial","",12)
    pdf.ln(5)
    pdf.cell(0,10,f"Name: {name}",ln=True)
    pdf.cell(0,10,f"Age: {age}",ln=True)
    pdf.cell(0,10,f"Dose: {dose} mg/kg",ln=True)
    pdf.cell(0,10,f"Diagnosis: {diagnosis}",ln=True)
    pdf.cell(0,10,f"Prescribed meds: {meds}",ln=True)
    pdf.multi_cell(0,10,f"AI Analysis & Recommendation:\n{result}")
    filename=f"{name.replace(' ','_')}_report.pdf"
    pdf.output(filename)
    return filename

