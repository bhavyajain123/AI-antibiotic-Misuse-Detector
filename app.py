# ============================================================
# RULE-BASED MISUSE DETECTION
# ============================================================

def detect_misuse(row):

    diagnosis = str(
        row["diagnosis_text"]
    ).lower()

    medication = str(
        row["meds"]
    ).lower()

    dose = float(
        row["dose_mg_per_kg"]
    )

    # Antibiotic with likely viral infection
    if "viral" in diagnosis and medication not in [
        "none",
        "",
        "na",
        "no"
    ]:
        return 1

    # No antibiotic recorded for pneumonia
    if "pneumonia" in diagnosis and medication in [
        "none",
        "",
        "na",
        "no"
    ]:
        return 1

    # Prototype high-dose threshold
    if dose > 40:
        return 1

    return 0


df["misuse_flag"] = df.apply(
    detect_misuse,
    axis=1
)


