def predict_misuse(age,dose,prior_antibiotic,fever,diagnosis_text,meds,lang="English"):
    misuse_type = ""
    if "viral" in diagnosis_text.lower() and meds != "none":
        misuse_type = "Antibiotic for viral infection"
